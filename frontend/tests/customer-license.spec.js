import fs from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('客户 License 配置、机台型号联动和历史文件下载', async ({ page }) => {
  test.setTimeout(120000)
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', e => errors.push(String(e)))
  const login = await page.request.post('/api/auth/login', { data: { username: 'admin', password: 'admin123' } })
  const headers = { Authorization: `Bearer ${(await login.json()).access_token}` }
  const original = await (await page.request.get('/api/config', { headers })).json()
  const key = String(Date.now())
  const customer = await (await page.request.post('/api/customers', { headers, data: { code: 'LIC-' + key } })).json()
  let machine
  const select = async (scope, label, value) => {
    await scope.locator('.el-select').filter({ has: page.getByRole('combobox', { name: label, exact: true }) }).click()
    await page.getByRole('option', { name: value, exact: true }).click()
  }
  try {
    await page.goto('/login')
    await page.getByPlaceholder('用户名').fill('admin')
    await page.getByPlaceholder('密码').fill('admin123')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await expect(page.locator('.el-main')).toBeVisible()
    await page.goto('/customers')
    await page.getByRole('button', { name: '客户面信息配置', exact: true }).click()
    let dialog = page.getByRole('dialog', { name: '客户面信息配置', exact: true })
    for (const [label, value] of [['机台类型', 'YLS-测试-' + key], ['产率包', '产率-' + key], ['高阶算法特性', '算法-' + key], ['可选特性', '特性-' + key]]) {
      const combo = dialog.getByRole('combobox', { name: label + '配置', exact: true })
      await combo.fill(value)
      await page.getByRole('option', { name: value, exact: true }).click()
      await combo.press('Escape')
    }
    await dialog.getByRole('button', { name: '保存配置', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await page.goto('/customer-status')
    await page.getByRole('button', { name: '编辑', exact: true }).first().click()
    await page.getByRole('button', { name: '新增', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '新增', exact: true })
    await dialog.locator('.el-form-item').filter({ has: page.getByText('机台编号', { exact: true }) }).getByRole('textbox').fill('M-' + key)
    await dialog.locator('.el-form-item').filter({ has: page.getByText('客户', { exact: true }) }).getByRole('combobox').click()
    await page.getByRole('option', { name: customer.code, exact: true }).click()
    await select(dialog, '机台型号', 'YLS-测试-' + key)
    const created = page.waitForResponse(r => r.url().endsWith('/api/customer-status') && r.request().method() === 'POST')
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    const response = await created
    expect(response.ok(), await response.text()).toBeTruthy()
    machine = await response.json()
    await expect(dialog).not.toBeVisible()
    await page.goto(`/customers/${customer.id}`)
    const block = page.locator('.license-block')
    await block.getByRole('button', { name: '新增 License', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '新增 License', exact: true })
    await dialog.getByRole('textbox', { name: 'ToolID（网元名称）', exact: true }).fill('NE-' + key)
    await dialog.getByRole('textbox', { name: 'UUID', exact: true }).fill('UUID-' + key)
    await select(dialog, '产率包', '产率-' + key)
    await select(dialog, '高阶算法特性', '算法-' + key)
    await select(dialog, '可选特性', '特性-' + key)
    await page.keyboard.press('Escape')
    await dialog.locator('input[type=file]').setInputFiles({ name: 'initial.lic', mimeType: 'application/octet-stream', buffer: Buffer.from([0, 255, 12, 31]) })
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    let row = block.getByRole('row').filter({ hasText: 'initial.lic' })
    await expect(row).toContainText('V1')
    const tool = row.getByRole('textbox', { name: 'ToolID（网元名称）', exact: true })
    await tool.fill('EDIT-' + key)
    const updated = page.waitForResponse(r => /\/api\/licenses\/\d+$/.test(r.url()) && r.request().method() === 'PUT')
    await tool.press('Tab')
    expect((await updated).ok()).toBeTruthy()
    await expect(tool).toHaveValue('EDIT-' + key)
    const modelUpdate = page.waitForResponse(r => /\/api\/customer-status\/\d+$/.test(r.url()) && r.request().method() === 'PUT')
    await select(row, '机台类型', 'YLS5000Y')
    expect((await modelUpdate).ok()).toBeTruthy()
    await expect(block.locator('.machine-model')).toContainText('YLS5000Y')
    await row.getByRole('button', { name: '更新文件', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '上传 License 新版本', exact: true })
    await dialog.locator('input[type=file]').setInputFiles({ name: 'replacement.bin', mimeType: 'application/octet-stream', buffer: Buffer.from([9, 0, 255, 7]) })
    await dialog.getByPlaceholder('本次变更说明').fill('更新授权')
    await dialog.getByRole('button', { name: '上传新版本', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await page.reload()
    row = block.getByRole('row').filter({ hasText: 'replacement.bin' })
    await expect(row).toContainText('V2')
    await expect(row.getByRole('textbox', { name: 'ToolID（网元名称）', exact: true })).toHaveValue('EDIT-' + key)
    await row.getByRole('button', { name: '变更历史', exact: true }).click()
    const drawer = page.getByRole('dialog', { name: 'License 变更历史', exact: true })
    const old = drawer.getByRole('row').filter({ hasText: 'initial.lic' })
    await old.click()
    await expect(drawer).toContainText('V1 授权信息快照')
    await expect(drawer.locator('.el-descriptions')).toContainText('YLS-测试-' + key)
    await expect(drawer.locator('.el-descriptions')).toContainText('NE-' + key)
    const downloaded = page.waitForEvent('download')
    await old.getByRole('button', { name: '下载', exact: true }).click()
    const download = await downloaded
    expect(download.suggestedFilename()).toBe('initial.lic')
    expect(await fs.readFile(await download.path())).toEqual(Buffer.from([0, 255, 12, 31]))
    await drawer.getByRole('button', { name: '查看字段修改记录', exact: true }).click()
    const changes = page.getByRole('dialog', { name: '修订历史', exact: true })
    await expect(changes).toContainText('EDIT-' + key)
    await expect(changes).toContainText('NE-' + key)
    await changes.getByRole('button', { name: 'Close this dialog' }).click()
    await drawer.getByRole('button', { name: 'Close this dialog' }).click()
    await page.setViewportSize({ width: 1366, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.goto('/customer-status')
    await expect(page.getByRole('row').filter({ hasText: 'M-' + key })).toContainText('YLS5000Y')
    expect(errors).toEqual([])
  } finally {
    if (machine) await page.request.delete(`/api/customer-status/${machine.id}`, { headers })
    await page.request.delete(`/api/customers/${customer.id}`, { headers })
    await page.request.put('/api/config', { headers, data: original })
  }
})
