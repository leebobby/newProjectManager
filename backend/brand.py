"""导出配色的**单一来源**：PPT 与 Excel 共用一套，见 CLAUDE.md「导出与上传」。

取色逻辑对齐部门述职 PPT 模板，是「红定位、蓝分层、饱和色点灯」，
三者各管一件事，**不要互相借用**：

    红     只用在标题文字和标题下那条线上，一份文件里就这两处
    浅蓝   表头，把表头和正文分层
    红黄绿 只给状态格上底色，是整份文件唯一的饱和色，所以一眼扫得到

这里存 6 位十六进制字符串（openpyxl 直接吃）；`pptx_utils` 自己转成 `RGBColor`。

**不要在 pptx_utils / xlsx_io / xlsx_utils 里另写颜色字面量。**
历史上 Excel 清单走品牌蓝 #4073BA、专项 Excel 走华为红、PPT 又是另一套红，
同一批数据导成三种文件是三个配色——而每一份单独看都挺正常，
没人会把"两份文件不像一套材料"当成 bug 报上来。
"""

BRAND = "C7000B"          # 华为红：标题文字 + 标题下的横线
TEXT = "262626"           # 正文黑
MUTED = "808080"          # 副标题 / 页脚 / 附注
WHITE = "FFFFFF"
HEADER_BG = "D9E2F3"      # 表头：浅蓝灰
HEADER_TEXT = "1F242E"    # 表头黑字（底色浅，不用白字）
SECTION_BG = "D9D9D9"     # 章节行 / 分组行 / 合计行：中灰
BORDER = "BFBFBF"         # 中性灰细边框
# 斑马纹压到几乎看不见，并跟着表头走蓝灰一系。窄表白底就够认行，
# 但产品需求这类十几列的表全白时眼睛横扫会串行，所以保留。
ZEBRA = "F4F7FC"

# 状态点灯：**给格子上底色，不是给字上色**。
# 只染字色的话，一排进展列全是同字号小字，得逐格读才分得出来。
STATUS_FILLS = {
    "已完成": "92D050",   # 绿
    "已闭环": "92D050",
    "进行中": "FFD966",   # 黄
    "已延期": "FF9999",   # 红
    # 「已变更」＝这条本轮不做了。导出**不剔这些行**（那是交付记录），
    # 灰底只是把它和还在推进的行分开，免得被当成进度算进去。
    "已变更": "D9D9D9",   # 灰
}
# 这两档故意不点灯：它们表达的是"这里没有进展"，
# 上了底色会和真有状态的格子一样抢眼，反而把真信号淹掉。
STATUS_TEXT = {
    "未开始": "909399",
    "不涉及": "B0B3B8",
}
# 点灯底色都是浅色，字一律用近黑；白字在黄底上等于没有。
STATUS_ON_FILL_TEXT = "1F242E"


def status_style(text):
    """一格文字的状态样式：(底色, 字色, 是否加粗)；不是状态词就 (None, None, False)。

    **精确匹配**，不做包含匹配：客户面的「现场关键事务」一格里可能写着
    "已完成三个模块联调"，模糊匹配会把整格染绿，而它其实还在进行中。
    """
    key = (text or "").strip()
    fill = STATUS_FILLS.get(key)
    if fill:
        return fill, STATUS_ON_FILL_TEXT, True
    muted = STATUS_TEXT.get(key)
    if muted:
        return None, muted, False
    return None, None, False
